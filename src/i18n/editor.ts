export function editorText(language: Language, key: EditorTranslationKey, parameters: Record<string, string | number> = {}): string {
  return (language === "en" ? editorEnglish[key] : editorChinese[key]).replace(/\{(\w+)\}/g, (placeholder, name: string) => String(parameters[name] ?? placeholder));
}