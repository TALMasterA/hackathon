export function assistantText(language: Language, key: AssistantTranslationKey, parameters: Record<string, string | number> = {}): string {
  return (language === "en" ? assistantEnglish[key] : assistantChinese[key]).replace(/\{(\w+)\}/g, (placeholder, name: string) => String(parameters[name] ?? placeholder));
}

export function isAssistantKey(key: string): key is AssistantTranslationKey {
  return key in assistantEnglish;
}
